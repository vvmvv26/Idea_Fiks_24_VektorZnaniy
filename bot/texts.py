def eta(seconds: int) -> str:
    if seconds < 60:
        return f"~{max(10, round(seconds / 10) * 10)} с"
    if seconds < 180:
        minutes, rest = divmod(round(seconds / 10) * 10, 60)
        return f"~{minutes} мин" + (f" {rest} с" if rest else "")
    return f"~{round(seconds / 60)} мин"


def wait_text(seconds: int, ahead: int) -> str:
    queue = f"\nПеред вами в очереди: {ahead}." if ahead else ""
    return f"⏳ Готовлю ответ. Примерное время ожидания: {eta(seconds)}.{queue}"


